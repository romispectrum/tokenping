import { readFileSync } from "node:fs";
import path from "node:path";
import { format, resolveConfig } from "prettier";
import { LOCALES, type Locale, PREFIXED_LOCALES, type PrefixedLocale } from "~~/i18n/locales";

// Every language has a client root in i18n/client/<locale>.tsx, and i18n/client/roots.tsx loads the root of each
// prefixed language on demand. They are generated from the templates below (`yarn locale-clients`), and
// scripts/localeClients.test.ts fails when a file on disk differs from its template. The routes themselves are not
// generated: English has app/(en), and every other language is served by app/(intl)/[lang].

export const PACKAGE_ROOT = path.resolve(__dirname, "..");

/** The message areas client components read (i18n/client/messages.ts). */
const CLIENT_AREAS = ["alerts", "blog", "calculator", "common", "dashboard", "morpho"] as const;

const clientRoot = (locale: Locale) => `
"use client";

import type { ReactNode } from "react";
import { ClientRoot } from "~~/components/ClientRoot";
${CLIENT_AREAS.map(area => `import { MESSAGES as ${area} } from "~~/i18n/messages/${area}/${locale}";`).join("\n")}

const MESSAGES = { ${CLIENT_AREAS.join(", ")} };

/** The ${locale} client root: the only module that brings ${locale} strings into the browser. */
export const LocaleRoot = ({ children }: { children: ReactNode }) => (
  <ClientRoot locale="${locale}" messages={MESSAGES}>
    {children}
  </ClientRoot>
);
`;

const dynamicRoot = (locale: PrefixedLocale) =>
  `  ${locale}: dynamic(() => import("~~/i18n/client/${locale}").then(module => module.LocaleRoot)),`;

const prefixedRoots = (locales: readonly PrefixedLocale[]) => `
"use client";

// Generated by \`yarn locale-clients\` (scripts/localeClients.ts): do not edit.
import type { ComponentType, ReactNode } from "react";
import dynamic from "next/dynamic";
import type { PrefixedLocale } from "~~/i18n/locales";

type Root = ComponentType<{ children: ReactNode }>;

// One import() per language, so each language's client root and strings are a chunk of their own that a page loads
// only when it renders that language. Static imports of every root would put them all in the shared layout's bundle.
// Server-rendered as usual: next/dynamic preloads the chunk of the root a page renders.
const ROOTS: Record<PrefixedLocale, Root> = {
${locales.map(dynamicRoot).join("\n")}
};

/** The client root of a prefixed language (app/(intl)/[lang]/layout.tsx). English mounts its own root directly. */
export const PrefixedLocaleRoot = ({ locale, children }: { locale: PrefixedLocale; children: ReactNode }) => {
  const LocaleRoot = ROOTS[locale];
  return <LocaleRoot>{children}</LocaleRoot>;
};
`;

/** Every generated file, by path relative to the package, before formatting. */
export const localeClientSources = (locales: readonly Locale[] = LOCALES): Record<string, string> => ({
  ...Object.fromEntries(locales.map(locale => [`i18n/client/${locale}.tsx`, clientRoot(locale)])),
  "i18n/client/roots.tsx": prefixedRoots(PREFIXED_LOCALES.filter(locale => locales.includes(locale))),
});

/** The generated files, formatted with the package's Prettier config. */
export const localeClientFiles = async (locales: readonly Locale[] = LOCALES): Promise<Record<string, string>> => {
  const entries = await Promise.all(
    Object.entries(localeClientSources(locales)).map(async ([file, source]) => {
      const filepath = path.join(PACKAGE_ROOT, file);
      const options = await resolveConfig(filepath);
      const text = source.replace(/\n{3,}/g, "\n\n").trimStart();
      return [file, await format(text, { ...options, filepath })] as const;
    }),
  );
  return Object.fromEntries(entries);
};

/** What is on disk at a generated path, or undefined. */
export const readGenerated = (file: string) => {
  try {
    return readFileSync(path.join(PACKAGE_ROOT, file), "utf8");
  } catch {
    return undefined;
  }
};
