import { existsSync } from "node:fs";
import path from "node:path";
import { format, resolveConfig } from "prettier";
import { DEFAULT_LOCALE, LOCALES, type Locale } from "~~/i18n/locales";
import { POST_SLUGS } from "~~/i18n/postSlugs";

// content/blog/posts.ts imports every post of every language. It is generated from i18n/postSlugs.ts and the files
// in content/blog (`yarn blog-index`), and scripts/blogIndex.test.ts fails when it is stale: a post's order is its
// place in POST_SLUGS, and a translation is listed once its file exists.

const PACKAGE_ROOT = path.resolve(__dirname, "..");
export const BLOG_INDEX_FILE = "content/blog/posts.ts";

const pascal = (text: string) => text.replace(/(?:^|-)([a-z0-9])/g, (_, letter: string) => letter.toUpperCase());

/** The post file of `key` in `locale`, relative to content/blog. */
const postFile = (key: string, locale: Locale) =>
  locale === DEFAULT_LOCALE ? `${POST_SLUGS[key].en}.mdx` : `${locale}/${POST_SLUGS[key][locale]}.mdx`;

const identifiers = (key: string, locale: Locale) => {
  const component = `${locale === DEFAULT_LOCALE ? "" : pascal(locale)}${pascal(key)}`;
  return { component, meta: component[0].toLowerCase() + component.slice(1) };
};

/** The posts of each language that have a file, in POST_SLUGS order. */
const postsByLocale = () =>
  Object.fromEntries(
    LOCALES.map(locale => [
      locale,
      Object.keys(POST_SLUGS).filter(key => existsSync(path.join(PACKAGE_ROOT, "content/blog", postFile(key, locale)))),
    ]),
  ) as Record<Locale, string[]>;

export const blogIndexSource = async () => {
  const posts = postsByLocale();
  const imports = LOCALES.flatMap(locale =>
    posts[locale].map(key => {
      const { component, meta } = identifiers(key, locale);
      return `import ${component}, { meta as ${meta} } from "~~/content/blog/${postFile(key, locale)}";`;
    }),
  );
  const arrays = LOCALES.map(locale => {
    const entries = posts[locale].map(key => {
      const { component, meta } = identifiers(key, locale);
      return `{ meta: ${meta}, Content: ${component} },`;
    });
    return `  ${locale}: [\n${entries.join("\n")}\n  ],`;
  });
  const source = `// Generated by \`yarn blog-index\` (scripts/blogIndex.ts) from i18n/postSlugs.ts and the post files: do not edit.
${imports.join("\n")}
import type { Post } from "~~/content/blog/types";
import type { Localized } from "~~/i18n/locales";

/** Every post of each language, hub first, in the order of i18n/postSlugs.ts. */
export const POSTS_BY_LOCALE: Localized<readonly Post[]> = {
${arrays.join("\n")}
};
`;
  const filepath = path.join(PACKAGE_ROOT, BLOG_INDEX_FILE);
  return format(source, { ...(await resolveConfig(filepath)), filepath });
};
